@pytest.mark.parametrize('html',[
 # Real article that discusses CloudFront blocks must never be rejected: long visible body.
 '<html><head><title>CloudFront notes</title></head><body><article><h1>CloudFront notes</h1><p>'+('We discuss the request could not be satisfied page at length. '*40)+'</p></article></body></html>',
 # Article title literally mentioning attention-required must pass: real body, no Ray id.
 '<html><head><title>Why Cloudflare says attention required</title></head><body><article><h1>Why Cloudflare says attention required</h1><p>'+('A field guide to attention required interstitials and what they mean. '*30)+'</p></article></body></html>',
 # Article mentioning Aliyun WAF documentation: heading exists but no WAF fingerprints.
 '<html><head><title>Aliyun WAF internals</title></head><body><article><h1>Aliyun WAF internals</h1><p>'+('The aliyun_waf module handles challenges in their stack. '*30)+'</p></article></body></html>',
 # The URL-rejected wording inside a >=5KB page is treated as content, not a barrier.
 '<html><head><title>Edge support diary</title></head><body><p>'+('The requested URL was rejected by the load balancer in this documented case. '*60)+'</p></body></html>',
 # Empty-result content page (quoting "no results") is content, not a barrier.
 '<html><head><title>Search</title></head><body><div class="empty">We\'re sorry, no results were found for your search: "China power ranking".</div></body></html>',
])
def test_long_or_content_pages_are_not_access_barriers(html):
 reject_access_page(html)

